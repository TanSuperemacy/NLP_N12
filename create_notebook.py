    "])\n",
    "\n",
    "# 2. PIPELINE CHỐNG RÒ RỈ DỮ LIỆU (ZERO DATA LEAKAGE)\n",
    "pipe = Pipeline([\n",
    "    ('tfidf', features),\n",
    "    ('svm', LinearSVC(random_state=42, max_iter=5000, class_weight='balanced'))\n",
    "])\n",
    "\n",
